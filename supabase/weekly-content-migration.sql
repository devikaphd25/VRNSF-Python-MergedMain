-- Associate Lesson 1's video, challenge, and briefing with Lesson 1. Games
-- belong to the entire week, so their lesson_id intentionally remains null.
update public.week_activities activity
set lesson_id = lesson.id
from public.week_lessons lesson
join public.learning_weeks week on week.id = lesson.week_id
where activity.week_id = week.id
  and week.week_number = 1
  and lesson.lesson_number = 1
  and activity.activity_order between 1 and 3;

update public.week_activities activity
set lesson_id = null
from public.learning_weeks week
where activity.week_id = week.id
  and week.week_number = 1
  and activity.activity_type = 'game';

