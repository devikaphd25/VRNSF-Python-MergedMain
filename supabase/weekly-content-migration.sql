-- Remove only the unused placeholder created by the earlier version of this
-- migration. Real/published weeks and all classroom history are preserved.
delete from public.learning_weeks week
where week.week_number = 2
  and week.title = 'Variables'
  and week.is_published = false
  and not exists (
    select 1
    from public.week_activities activity
    where activity.week_id = week.id
  );

-- Week 1 contains three lessons. Their media and activities can be edited
-- without changing the application code once the content loader is enabled.
insert into public.week_lessons (
    week_id,
    lesson_number,
    title,
    description
)
select
    week.id,
    lesson.lesson_number,
    lesson.title,
    lesson.description
from public.learning_weeks week
cross join (
    values
      (1, 'Meet the Machine', 'Computer foundations and the Python learning roadmap.'),
      (2, 'Why Python Powers Modern Apps', 'Python accessibility, industry impact, versatility, and modern applications.'),
      (3, 'Hardware and Software', 'Computer components, input and output, memory, storage, and software categories.')
) as lesson(lesson_number, title, description)
where week.week_number = 1
on conflict (week_id, lesson_number) do update
set title = excluded.title,
    description = excluded.description;

