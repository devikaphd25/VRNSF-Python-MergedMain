-- Weekly learning content for the VR classroom.
-- Run after room-code-migration.sql and app-data-migration.sql.
-- This migration is additive: existing questions, responses, rooms, and game
-- results remain valid and receive nullable links to the new content model.

create table if not exists public.learning_weeks (
    id bigint generated by default as identity primary key,
    week_number integer not null unique check (week_number > 0),
    title text not null,
    description text not null default '',
    is_published boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.week_activities (
    id bigint generated by default as identity primary key,
    week_id bigint not null
        references public.learning_weeks(id) on delete cascade,
    activity_order integer not null check (activity_order > 0),
    activity_type text not null
        check (activity_type in ('presentation', 'challenge', 'game', 'briefing')),
    title text not null,
    description text not null default '',
    -- A stable application identifier, for example python-type-lab.
    game_key text,
    -- Public paths or hosted URLs for slides, videos, and briefing images.
    asset_path text,
    -- Optional 360-degree environment used only by this activity.
    environment_path text,
    duration_seconds integer check (duration_seconds is null or duration_seconds > 0),
    settings jsonb not null default '{}'::jsonb,
    is_enabled boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (week_id, activity_order)
);

create index if not exists week_activities_week_id_idx
on public.week_activities(week_id, activity_order);

-- A challenge can contain one or more existing quiz_questions. Responses do
-- not need another week column: quiz_responses -> quiz_questions -> activity
-- -> week provides one consistent relationship without duplicated data.
alter table public.quiz_questions
add column if not exists activity_id bigint
references public.week_activities(id)
on delete set null;

create index if not exists quiz_questions_activity_id_idx
on public.quiz_questions(activity_id);

-- Connect a saved game result to the weekly game that produced it.
alter table public.game_results
add column if not exists activity_id bigint
references public.week_activities(id)
on delete set null;

create index if not exists game_results_activity_id_idx
on public.game_results(activity_id);

-- Records which week's content the instructor selected for a classroom.
alter table public.rooms
add column if not exists active_week_id bigint
references public.learning_weeks(id)
on delete set null;

create index if not exists rooms_active_week_id_idx
on public.rooms(active_week_id);

alter table public.learning_weeks enable row level security;
alter table public.week_activities enable row level security;

-- The Node server uses its server-only Supabase secret key. No direct browser
