-- Initial rows matching the two menu pages currently included in the app.
insert into public.learning_weeks (
    week_number,
    title,
    description,
    is_published
)
values
    (1, 'Literal Computers and the Five Computer Parts', 'CPU, RAM, storage, input, output, challenge, game, and debrief.', true),
    (2, 'Variables', 'Variables and data-types learning activities.', false)
on conflict (week_number) do update
set title = excluded.title,
    description = excluded.description;

insert into public.week_activities (
    week_id,
    activity_order,
    activity_type,
    title,
    description,
    game_key,
    asset_path,
    environment_path,
    duration_seconds
)
select
    week.id,
    activity.activity_order,
    activity.activity_type,
    activity.title,
    activity.description,
    activity.game_key,
    activity.asset_path,
    activity.environment_path,
    activity.duration_seconds
from public.learning_weeks week
cross join (
    values
      (1, 'presentation', 'Literal Computers and the Five Computer Parts', 'Present CPU, RAM, storage, input, and output.', null, '/videos/week-1/w1-1-final-video.mp4', null, null),
      (2, 'challenge', 'Five Parts Challenge', 'Identify the job of each computer component.', null, null, './textures/quiz/quick-challenge-space-360.png', 60),
      (3, 'game', 'Variable Sorting', 'Sort Python values into the correct data-type bins.', 'python-type-lab', null, null, null),
      (4, 'briefing', 'Five Parts Debrief', 'Review the five-part computer model.', null, './images/briefings/week-1/five-parts-of-every-computer-debrief.png', null, null)
) as activity(
    activity_order,
    activity_type,
    title,
    description,
    game_key,
    asset_path,
    environment_path,
    duration_seconds
)
where week.week_number = 1
on conflict (week_id, activity_order) do update
set activity_type = excluded.activity_type,
    title = excluded.title,
    description = excluded.description,
    game_key = excluded.game_key,
    asset_path = excluded.asset_path,
    environment_path = excluded.environment_path,
    duration_seconds = excluded.duration_seconds;

-- Final Week 1 Lesson 2 lecture video. The lesson-aware curriculum tables
-- are added by the current hosted schema. Keep this update here so rerunning
-- the curriculum migration preserves the production Lesson 2 asset.
do $$
begin
  if to_regclass('public.week_lessons') is not null then
    update public.week_activities activity
    set asset_path = '/videos/week-1/w1-2-final-video.mp4',
        updated_at = now()
    from public.week_lessons lesson,
         public.learning_weeks week
    where activity.lesson_id = lesson.id
      and lesson.week_id = week.id
      and week.week_number = 1
      and lesson.lesson_number = 2
      and activity.activity_type = 'presentation';
  end if;
end
$$;
