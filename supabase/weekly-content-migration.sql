set activity_id = activity.id
from public.week_activities activity
join public.learning_weeks week on week.id = activity.week_id
where question.deck = 'week-1'
  and week.week_number = 1
  and activity.activity_type = 'challenge'
  and activity.activity_order = case question.slide_number
    when 1 then 2
    when 2 then 6
    when 3 then 9
    else -1
  end;
