const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const config=JSON.parse(fs.readFileSync('apk/tooling/bubblewrap-config.json','utf8'));
const env={...process.env,JAVA_HOME:path.join(config.jdkPath,'Contents/Home')};
const tools=path.join(config.androidSdkPath,'build-tools/35.0.0');
const apk=path.resolve('apk/UMES-VR-Classroom-test.apk');
const verification=execFileSync(path.join(tools,'apksigner'),['verify','--verbose','--print-certs',apk],{env,encoding:'utf8'});
const fingerprint=verification.match(/certificate SHA-256 digest:\s*([a-f0-9]+)/i)?.[1];
const links=JSON.parse(fs.readFileSync('public/.well-known/assetlinks.json','utf8'));
if(!fingerprint||links[0].target.sha256_cert_fingerprints[0].replaceAll(':','').toLowerCase()!==fingerprint.toLowerCase())throw Error('APK certificate differs from Digital Asset Links');
const badging=execFileSync(path.join(tools,'aapt'),['dump','badging',apk],{env,encoding:'utf8'});
if(!badging.includes("package: name='edu.umes.vrclassroom.test'")||!badging.includes("targetSdkVersion:'32'"))throw Error('Unexpected APK package or target SDK');
const manifest=execFileSync(path.join(tools,'aapt'),['dump','xmltree',apk,'AndroidManifest.xml'],{env,encoding:'utf8'});
if(!manifest.includes('horizonos.pwa.APP_MODE')||!manifest.includes('com.oculus.intent.category.VR'))throw Error('Immersive Quest metadata missing');
fs.mkdirSync('dist/downloads',{recursive:true});
fs.copyFileSync(apk,'dist/downloads/UMES-VR-Classroom-test.apk');
console.log(verification.split('\n').filter(line=>line.startsWith('Verifies')||line.startsWith('Verified using')).join('\n'));
console.log(badging.split('\n').filter(line=>line.startsWith('package:')||line.startsWith('sdkVersion:')||line.startsWith('targetSdkVersion:')||line.startsWith('application-label:')).join('\n'));
console.log('Certificate matches hosted Digital Asset Links. Immersive Quest metadata is present.');
console.log(`APK size: ${(fs.statSync(apk).size/1048576).toFixed(1)} MB`);

const versionCode = Number(badging.match(/versionCode='(\d+)'/)?.[1]);
if (!versionCode) throw Error('APK version code could not be read.');
const filename = `UMES-VR-Classroom-test-v${versionCode}.apk`;
fs.copyFileSync(apk, path.join('apk', filename));
fs.copyFileSync(apk, path.join('dist/downloads', filename));
const runtime = JSON.parse(fs.readFileSync('apk/runtime.json', 'utf8'));
console.log(`Device Manager download URL: ${runtime.origin}/downloads/${filename}`);
